// Signs that an agile process has become a formality, with fixes.
export function AgileTraps() {
  const [i, setI] = useState(0);
  const t = traps[i];

  return (
    <Figure
      title="Agile на папері"
      lead="Шість ознак, що гнучкий підхід став формальністю."
      caption="Натисніть на ознаку, щоб побачити, чому вона шкодить і що з нею робити."
    >
      <div className="grid gap-2 @md:grid-cols-2" role="group" aria-label="Ознака">
        {traps.map((x, k) => (
          <button
            key={x.sign}
            type="button"
            aria-pressed={k === i}
            onClick={() => setI(k)}
            className={`rounded-[4px] border px-3 py-2.5 text-left text-sm font-medium transition-colors duration-200 ${
              k === i ? "border-accent bg-accent-soft" : "border-transparent bg-foreground/[0.04] hover:bg-foreground/[0.08]"
            }`}
          >
            {x.sign}
          </button>
        ))}
      </div>

      <div className="mt-4 rounded-[4px] bg-accent-soft p-4 leading-relaxed" aria-live="polite">
        <p>
          <strong>Чому шкодить:</strong> {t.why}
        </p>
        <p className="mt-2">
          <strong>Що робити:</strong> {t.fix}
        </p>
      </div>
    </Figure>
  );
}
