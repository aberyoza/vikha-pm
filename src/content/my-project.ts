export type Idea = {
  what: (typeof WHAT)[number];
  who: (typeof WHO)[number];
  name: string;
  hints: Record<ValueStep, string[]>;
  // Suggested answers to APPROACH_QUESTIONS (module 3), by option index.
  approach: number[];
  // Module 4: suggested answers to INVEST_QUESTIONS and hints for the free text.
  invest: { answers: number[]; alternative: string[]; goal: string[] };
  // Module 5: people around the project with suggested analysis.
  people: Person[];
  // Module 6: the sponsor and suggested answers to RULE_QUESTIONS.
  rules: { sponsor: string; answers: number[] };
  // Module 7: suggested blocks of work and what stays out of the project.
  scope: { blocks: string[]; out: string[] };
  // Module 8: suggested milestones and three estimates of the whole project, in weeks.
  schedule: { milestones: { name: string; week: number }[]; a: number; m: number; b: number };
  // Module 9: suggested costs of the scope blocks, by block index, and the reserve in percent.
  budget: { costs: number[]; reserve: number };
  // Module 10: suggested roles and, by block index, who does the block and who answers for it.
  team: { roles: string[]; raci: [string, string][] };
  // Module 11: three suggested risks, already described and assessed.
  risks: ProjectRisk[];
  // Module 12: three suggested quality requirements and who may stop the launch.
  quality: { metrics: ProjectMetric[]; stop: string };
  // Module 13: the suggested method, the scope blocks already in work, the limit and the rhythm.
  board: { method: string; doing: number[]; limit: number; rhythm: string };
  // Module 14: the measure with its target, an early sign, months of the checks and what to do if it lags.
  benefit: { metric: string; early: string; checks: number[]; behind: string };
};

// Module 12: one requirement to the result of the reader's project.
export type ProjectMetric = { name: string; target: string; check: string; who: string };

// Module 11: one risk of the reader's project, as a line of a small register.
export type ProjectRisk = {
  kind: "threat" | "opportunity";
  cause: string;
  event: string;
  effect: string;
  p: number;
  i: number;
  response: string;
  cost: number;
  owner: string;
  trigger: string;
};

// Module 5: one row of the stakeholder register. Levels index ENGAGEMENT.
export type Person = { name: string; power: boolean; interest: boolean; now: number; want: number };

const person = (name: string, power: 0 | 1, interest: 0 | 1, now: number, want: number): Person => ({
  name,
  power: !!power,
  interest: !!interest,
  now,
  want,
});

