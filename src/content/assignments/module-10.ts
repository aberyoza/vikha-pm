export const weightedScores = (w: Record<Criterion, number>) => {
  const total = w.price + w.quality + w.time || 1;
  return VENDORS.map((v) => ({ name: v.name, sum: (v.scores.price * w.price + v.scores.quality * w.quality + v.scores.time * w.time) / total }));
};

