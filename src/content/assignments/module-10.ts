export function reschedule(mechanics: number, server: number) {
  const notBefore: Record<number, number> = { [MECHANICS]: mechanics - 1, [SERVER]: server - 1 };
  const ef = new Map<number, number>();
  const tasks = TASKS.map((t) => {
    const es = Math.max(notBefore[t.id] ?? 0, ...t.after.map((p) => ef.get(p)!));
    ef.set(t.id, es + t.weeks);
    return { ...t, es, ef: es + t.weeks } as Pick<Scheduled, "id" | "name" | "weeks" | "es" | "ef">;
  });
  return { tasks, total: Math.max(...ef.values()) };
}

// How many of the programmer's works run in each week, from the first.
export const programmerLoad = (tasks: ReturnType<typeof reschedule>["tasks"]) =>
  Array.from({ length: CALENDAR_WEEKS }, (_, w) => tasks.filter((t) => PROGRAMMER.includes(t.id) && t.es <= w && w < t.ef).length);

