export type BoardCard = { task: string; age: number };
export type BoardDay = { queue: string[]; doing: BoardCard[]; done: BoardCard[] };

// The board after `day` finished days. Those in work at the start have been there
// for a while already, so every finished task has taken exactly `limit` days.
export function boardAt(limit: number, day: number): BoardDay {
  const done = BOARD_TASKS.slice(0, day).map((task) => ({ task, age: limit }));
  const doing = BOARD_TASKS.slice(day, day + limit).map((task, k) => ({ task, age: limit - 1 - k }));
  return { queue: BOARD_TASKS.slice(day + limit), doing, done };
}

